#!/usr/bin/env node
/**
 * Keeps `src/version.ts` in sync with the version declared in `package.json`.
 *
 * `package.json` is the single source of truth for the library version. This script is executed
 * automatically by `npm run version` (after Changesets bumps the package) and by `npm run build`,
 * so the exported `designSystemVersion` never has to be edited by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
const target = resolve(root, 'src/version.ts');

const content = `// This file is generated by scripts/sync-version.mjs from package.json. Do not edit manually.

/**
 * Current version of the El Lobo Design System, mirrored from package.json.
 */
export const designSystemVersion = '${pkg.version}';
`;

let current = '';
try {
  current = readFileSync(target, 'utf8');
} catch {
  current = '';
}

if (current !== content) {
  writeFileSync(target, content);
  console.log(`[sync-version] src/version.ts updated to ${pkg.version}`);
} else {
  console.log(`[sync-version] src/version.ts already at ${pkg.version}`);
}
